export function isExcludedContentTopic(value: string) {
  const normalized = stripHtml(value || "").replace(/\s+/g, " ").toLowerCase();
  return EXCLUDED_CONTENT_TERMS.some((term) => normalized.includes(term.toLowerCase()));
}

